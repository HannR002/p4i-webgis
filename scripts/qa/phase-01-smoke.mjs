import { mkdir } from 'node:fs/promises';
import path from 'node:path';
const { chromium } = await import(process.env.P4I_PLAYWRIGHT_MODULE || 'playwright-core');
const artifactDir = path.resolve(process.env.P4I_QA_ARTIFACTS || '/tmp/p4i-phase-01');
await mkdir(artifactDir, { recursive: true });
const chromiumPath = process.env.P4I_CHROMIUM || '/usr/bin/chromium';
import assert from 'node:assert/strict';
(async () => {
  const browser = await chromium.launch({ executablePath: chromiumPath, headless: true, args: ['--no-sandbox'] });
  const context = await browser.newContext({ viewport: { width: 1480, height: 960 }, acceptDownloads: true });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('http://localhost:3000/spatial/home', { waitUntil: 'domcontentloaded' });
  await page.getByText('MODE DEMO ·').waitFor();
  await page.screenshot({ path: path.join(artifactDir, 'portal-home.png'), fullPage: true });
  await page.goto('http://localhost:3000/spatial/webmap');
  assert.equal(await page.locator('.gis-webmap').count(), 6);
  await page.getByLabel('Cari webmap').fill('Curah');
  assert.equal(await page.locator('.gis-webmap').count(), 1);
  await page.getByRole('link', { name: /^Lihat Peta/ }).click();
  await page.getByText('Layer aktif (2)').waitFor();
  await page.getByLabel('Basemap', { exact: true }).selectOption('none');
  await page.waitForFunction(() => document.querySelectorAll('img.leaflet-tile-loaded[src*="/api/gis/"]').length > 0);
  await page.screenshot({ path: path.join(artifactDir, 'map-workspace.png'), fullPage: true });
  await page.getByLabel('Opacity Curah hujan tahunan').fill('0.35');
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  assert.equal(await page.getByLabel('Opacity Curah hujan tahunan').inputValue(), '0.6');
  await page.getByRole('button', { name: 'Redo', exact: true }).click();
  assert.equal(await page.getByLabel('Opacity Curah hujan tahunan').inputValue(), '0.35');
  await page.getByLabel('Pilih area kajian').selectOption('demo-aoi-west');
  await page.getByRole('button', { name: 'Simpan draft', exact: true }).click();
  await page.getByRole('button', { name: 'Reset', exact: true }).click();
  await page.getByText('Layer aktif (0)').waitFor();
  await page.getByRole('button', { name: 'Buka', exact: true }).click();
  await page.getByText('Layer aktif (2)').waitFor();
  await page.getByRole('button', { name: 'Inspeksi piksel', exact: true }).click();
  const box = await page.locator('.leaflet-container').boundingBox();
  await page.mouse.click(box.x + box.width / 2 + 20, box.y + box.height / 2 + 20);
  await page.locator('.gis-pixel-card').first().waitFor();
  assert.match(await page.locator('.gis-pixel-value').first().textContent(), /mm\/tahun/);
  await page.screenshot({ path: path.join(artifactDir, 'pixel-inspector.png'), fullPage: true });
  await page.locator('.gis-tabs').getByRole('tab', { name: 'AI GIS', exact: true }).click();
  await page.getByLabel('Instruksi GIS').fill('Buat peta curah hujan dan kemiringan dengan batas kecamatan');
  await page.getByRole('button', { name: 'Kirim instruksi' }).click();
  await page.getByRole('button', { name: 'Terapkan ke sesi peta' }).waitFor();
  await page.screenshot({ path: path.join(artifactDir, 'copilot-plan.png'), fullPage: true });
  await page.getByRole('button', { name: 'Terapkan ke sesi peta' }).click();
  await page.getByText('AI-generated map configuration', { exact: true }).waitFor();
  await page.locator('.gis-tabs').getByRole('tab', { name: 'Layer', exact: true }).click();
  await page.getByText('Layer aktif (3)').waitFor();
  await page.getByLabel('Basemap', { exact: true }).selectOption('none');
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await page.getByText('Layer aktif (2)').waitFor();
  await page.getByLabel('Basemap', { exact: true }).selectOption('none');
  const jsonDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Ekspor resep JSON' }).click();
  await (await jsonDownload).saveAs(path.join(artifactDir, 'example-map-recipe.json'));
  console.log('PASS: catalog search, layer opacity, Undo/Redo, AOI, draft save/reset/load, Pixel Inspector, Copilot plan/apply/undo, JSON export');
  // Browser image/PDF export checks use the synthetic layers with no external basemap.
  page.on('dialog', async d => { console.log('Export dialog:', d.message()); await d.dismiss(); });
  for (const [label,name] of [['Ekspor Citra Peta (PNG)','workspace-export.png'], ['Ekspor Ringkasan (PDF)','workspace-report.pdf']]) {
    const pending = page.waitForEvent('download', { timeout: 45000 });
    await page.getByRole('button', { name: label, exact: true }).click();
    await (await pending).saveAs(path.join(artifactDir, name));
    console.log('PASS:', label);
  }
  await page.goto('http://localhost:3000/spatial/data');
  await page.getByLabel('Jenis dataset').selectOption('raster');
  await page.locator('.gis-card').first().waitFor();
  assert.equal(await page.locator('.gis-card').count(), 4);
  const mobile = await context.newPage();
  await mobile.setViewportSize({width:390,height:844});
  mobile.on('pageerror', e => errors.push(e.message));
  await mobile.goto('http://localhost:3000/spatial/home');
  await mobile.getByRole('button', { name: 'Buka navigasi' }).click();
  assert.equal(await mobile.locator('dialog[open]').count(), 1);
  await mobile.getByRole('dialog', { name: 'Navigasi portal' }).getByRole('link', { name: 'Map Workspace', exact: true }).click();
  await mobile.locator('.leaflet-container').waitFor();
  await mobile.screenshot({ path: path.join(artifactDir, 'mobile-workspace.png'), fullPage: true });
  assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
  assert.deepEqual(errors, []);
  console.log('PASS: dataset filtering, responsive mobile navigation, no horizontal overflow; no JavaScript page errors');
  await browser.close();
})().catch(error => { console.error(error); process.exitCode = 1; });
